#!/usr/bin/perl -w

# Generate usys.S, the stubs for syscalls.

print "# generated by usys.pl - do not edit\n";

# 每个 entry 生成一个用户态系统调用桩：
#   把 SYS_xxx 编号放入 a7 -> ecall 陷入内核 -> syscall() 查表跳转。
# 内核把返回值放在 a0，桩函数执行 ret 返回用户态调用者。
print "#include \"kernel/syscall.h\"\n";

sub entry {
    my $prefix = "sys_";
    my $name = shift;
    print "# $name: 用户态系统调用桩（a7 <- SYS_$name，ecall 进入内核）\n";
    if ($name eq "sbrk") {
	print ".global $prefix$name\n";
	print "$prefix$name:\n";
    } else {
	print ".global $name\n";
	print "$name:\n";
    }
    print " li a7, SYS_${name}\n";   # 调用号放入 a7
    print " ecall\n";                # 进入内核，由 syscall() 分发
    print " ret\n";                  # 返回值已在 a0 中
}
	
